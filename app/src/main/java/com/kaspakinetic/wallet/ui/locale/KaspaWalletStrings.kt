private val DefaultKaspaWalletStrings = KaspaWalletStrings()

val LocalWalletStrings = compositionLocalOf<KaspaWalletStrings> { DefaultKaspaWalletStrings }

fun safeFormatLocalized(template: String, vararg args: Any?): String =
    runCatching { String.format(Locale.US, template, *args) }.getOrElse {
        // Never crash the UI thread if a locale template ever has a malformed format specifier
        var fallback = template
        args.forEach { arg ->
            fallback = fallback.replaceFirst("%s", arg?.toString().orEmpty())
                .replaceFirst("%d", arg?.toString().orEmpty())
        }
        fallback.replace("%%", "%")
    }

fun resolveKaspaWalletStrings(locale: Locale): KaspaWalletStrings {
    val lang = when (val raw = locale.language.lowercase(Locale.ROOT)) {
        "iw" -> "he"
        "in" -> "id"
        "ji" -> "yi"
        "no", "nn" -> "nb"
        "tl" -> "fil"
        else -> raw
    }
    val isTraditionalZh = lang == "zh" && (
        locale.country.equals("TW", ignoreCase = true) ||
            locale.country.equals("HK", ignoreCase = true) ||
            locale.country.equals("MO", ignoreCase = true) ||
            locale.script.equals("Hant", ignoreCase = true)
        )
    val key = if (isTraditionalZh) "zh-tw" else if (lang == "zh") "zh-cn" else lang
    return KaspaWalletTranslationsWest[key]
        ?: KaspaWalletTranslationsEast[key]
        ?: DefaultKaspaWalletStrings
}
